def _register_eager_ids():
    """Every id v1's own registry iterated eagerly, hard-coded as
    ``_V1_IDS`` -- everything except CLIRMatrix's regex-matched
    combinations (see the module docstring)."""
    for v1_id in _V1_IDS:
        node = V1Dataset(v1_id)
        legacy.register(node, module=__name__)
        target = _REPLACED_BY.get(v1_id)
        if target:
            legacy.add_edge(node, 'replaced_by', target)
            # So ir_datasets.v2.load(v1_id) still resolves the old way --
            # Graph.resolve_name reads this provider's own alias table like
            # any other's (see graph.py's module docstring).
            legacy.alias(v1_id, target)


def _register_all():
    _register_eager_ids()
    _register_clirmatrix_generators()


_register_all()
