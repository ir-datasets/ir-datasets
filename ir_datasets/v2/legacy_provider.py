"""The ``legacy:`` provider: every dataset id v1 ir_datasets ever registered,
each its own ``legacy:V1Dataset`` node -- so a pre-v2 id is addressable and
browsable in the graph on its own terms, not merely smuggled in as a
special-cased triple hanging off whichever v2 node it maps to (an earlier,
narrower version of this lived directly in ``ManifestProvider`` -- see
``registry.py``'s and ``graph.py``'s history). A ``legacy:replaced_by`` edge
points at that v2 node wherever one is actually known -- and, since a legacy
id is a real graph node here rather than a special-cased triple, resolving
one the old way (``ir_datasets.v2.load('antique/test')``) is just this
provider's own ``.alias()`` table (``_REPLACED_BY`` below, the same data as
each node's ``replaced_by`` edge), picked up by ``Graph.resolve_name`` like
any other provider's aliases.

Exposed as the ``legacy`` entry point in the ``ir_datasets.providers`` group
(see pyproject.toml), and added to the default graph when ``ir_datasets.v2``
is imported, same as ``irds``/``hf``/``clirmatrix``.

Two sources of names, both hard-coded here rather than discovered at import
time -- this module has no runtime dependency on v1 ``ir_datasets`` at all,
so it stays correct even against a v1 install that has since dropped or
renamed something:

* ``_V1_IDS``: the ~790 ids v1's own registry iterated eagerly
  (``ir_datasets.registry``) as of this writing -- a frozen snapshot, not a
  live query. Covers everything except CLIRMatrix, whose ~150,000 ids were
  matched by regex pattern at lookup time, not iterated (v1's own
  ``ir_datasets/datasets/clirmatrix.py`` registers them via
  ``registry.register_pattern``, which ``Registry.__iter__`` never walks).
  Each becomes a real, individually registered ``V1Dataset`` node -- cheap.
* ``_REPLACED_BY``: the subset of ``_V1_IDS`` that have a known v2
  counterpart -- a frozen snapshot of what every bundled dataset module's
  own (now-removed) ``irds.alias(...)`` call used to declare, transcribed
  here as the single place this mapping lives instead.

CLIRMatrix's own ~150,000 names are handled separately, by one ``Generator``
per v1 URL shape (``clirmatrix/{lang}``, .../multi8/..., .../bi139-base/...,
.../bi139-full/...) that reproduces v1's regex space directly
(language/split lists transcribed verbatim from v1's
``ir_datasets/datasets/clirmatrix.py``) rather than walking v1's live
``_patterns`` at runtime -- the same "report on demand, never eagerly build
150,000 Python objects" posture ``clirmatrix:`` itself uses for its *v2*
names (see ``clirmatrix_provider.py``'s own module docstring). None of these
carries a ``legacy:replaced_by`` edge: v2's CLIRMatrix deliberately never
aliased any v1 id -- a changed naming shape, ~150,000 of them -- see
``v2.datasets.clirmatrix``'s module docstring.
"""
from .base import Generator, Node, Param
from .registry import ManifestProvider

legacy = ManifestProvider('legacy')

V1_DATASET = legacy.node_type(
    'V1Dataset',
    desc='A dataset id from v1 ir_datasets, kept addressable in the graph '
         'even where it has no v2 counterpart.')
REPLACED_BY = legacy.edge_kind(
    'replaced_by', structural=False,
    desc='v1 dataset id -> the v2 node that replaced it (informational: a '
         'legacy id is bookkeeping, never part of anything\'s build DAG)')


class V1Dataset(Node):
    type = V1_DATASET


