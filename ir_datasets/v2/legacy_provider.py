def _clirmatrix_resolver(template):
    def resolve(**params):
        return V1Dataset(template.format(**params))
    return resolve


def _register_clirmatrix_generators():
    """The four v1 ``clirmatrix/...`` URL shapes (the bare ``clirmatrix``
    id itself is eagerly registered in v1, so it's covered by
    ``_register_eager_ids`` instead) -- see the module docstring.

    Each carries a ``replaced_by`` edge to its v2 ``clirmatrix:`` name too,
    by the same template-substitution mechanism ``clirmatrix:`` itself uses
    for its own structural edges (``Generator``'s ``edges=``, see
    ``v2.datasets.clirmatrix``) -- v1's shape maps onto v2's mechanically
    (docs: ``{lang}-docs``; a benchmark: ``{variant}-{doc_lang}-{query_lang}
    -{split}``, ``variant`` spelled without v1's internal hyphen -- see that
    module's own docstring on the two naming departures), so unlike the
    ~790 hand-listed ids this needs no finite mapping table to reproduce."""
    lang = Param(values=_CM_LANGS)
    multi8_lang = Param(values=_CM_MULTI8_LANGS)
    split = Param(values=_CM_SPLITS)
    # CLIR pairs a doc language against a *different* query language -- v1's
    # own pattern (``register_pattern``) accepts a same-language id like
    # ``clirmatrix/ar/multi8/ar/train`` too, but resolving it ``KeyError``s
    # (verified against v1 directly); it was never a real id, just an
    # unchecked corner of the regex. Applied here so this generator doesn't
    # claim a ``replaced_by`` edge to a v2 name that ``_bilingual_constraint``
    # (``v2.datasets.clirmatrix``) correctly never produces either.
    bilingual = lambda **p: p['doc_lang'] != p['query_lang']
    shapes = [
        ('clirmatrix/{doc_lang}', {'doc_lang': lang}, (),
         'clirmatrix:{doc_lang}-docs'),
        ('clirmatrix/{doc_lang}/multi8/{query_lang}/{split}',
         {'doc_lang': multi8_lang, 'query_lang': multi8_lang, 'split': split},
         (bilingual,), 'clirmatrix:multi8-{doc_lang}-{query_lang}-{split}'),
        ('clirmatrix/{doc_lang}/bi139-base/{query_lang}/{split}',
         {'doc_lang': lang, 'query_lang': lang, 'split': split},
         (bilingual,), 'clirmatrix:bi139base-{doc_lang}-{query_lang}-{split}'),
        ('clirmatrix/{doc_lang}/bi139-full/{query_lang}/{split}',
         {'doc_lang': lang, 'query_lang': lang, 'split': split},
         (bilingual,), 'clirmatrix:bi139full-{doc_lang}-{query_lang}-{split}'),
    ]
    for template, params, constraints, replaced_by_template in shapes:
        legacy.register_generator(Generator(
            template, params=params, type=V1_DATASET, constraints=constraints,
            resolver=_clirmatrix_resolver(template),
            edges=[('replaced_by', replaced_by_template)],
        ), module=__name__)


